#!/usr/bin/env python3
"""Download a pinned highlight.js release into vendor/ and build styles.css.

Run it from the repository root after changing VERSION or LANGUAGES, then
commit the result:  python3 scripts/vendor.py
"""

import re
import urllib.request
from pathlib import Path

VERSION = "11.12.0"
# Added on top of the ~40 languages in the standard highlight.min.js build.
LANGUAGES = ["dockerfile", "elixir", "haskell", "nix", "protobuf"]

BASE = f"https://cdn.jsdelivr.net/npm/@highlightjs/cdn-assets@{VERSION}"
ROOT = Path(__file__).resolve().parent.parent

# tmdview's theme selectors: dark when forced, or when the system is dark and light isn't forced.
DARK_SCOPES = [
    ('@media (prefers-color-scheme: dark) {', ':root:not([data-theme="light"])', "}"),
    ("", ':root[data-theme="dark"]', ""),
]


def fetch(path: str) -> str:
    with urllib.request.urlopen(f"{BASE}/{path}") as response:
        return response.read().decode("utf-8")


def scope(css: str, prefix: str) -> str:
    """Prefix every selector in a flat (no @-rules) stylesheet."""
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    rules = []
    for selectors, body in re.findall(r"([^{}]+)\{([^{}]*)\}", css):
        scoped = ", ".join(f"{prefix} {s.strip()}" for s in selectors.split(","))
        rules.append(f"{scoped} {{{body}}}")
    return "\n".join(rules)


def main() -> None:
    vendor = ROOT / "vendor"
    (vendor / "languages").mkdir(parents=True, exist_ok=True)
    (vendor / "highlight.min.js").write_text(fetch("highlight.min.js"))
    for lang in LANGUAGES:
        (vendor / "languages" / f"{lang}.min.js").write_text(fetch(f"languages/{lang}.min.js"))
    (vendor / "LICENSE").write_text(fetch("LICENSE"))

    light = scope(fetch("styles/github.min.css"), "pre.tmdview-plugin")
    dark = scope(fetch("styles/github-dark.min.css"), "pre.tmdview-plugin")
    parts = [
        f"/* highlight.js {VERSION} GitHub themes, scoped to tmdview's light and dark theme. */",
        "/* Generated by scripts/vendor.py; don't edit by hand. */",
        light,
    ]
    for open_, root, close in DARK_SCOPES:
        parts += [open_, scope(dark, root), close]
    # Keep tmdview's own code block background and padding.
    parts.append("pre.tmdview-plugin code.hljs { background: transparent !important; padding: 0 !important; }")
    (ROOT / "styles.css").write_text("\n".join(p for p in parts if p) + "\n")

    scripts = ["vendor/highlight.min.js"] + [f"vendor/languages/{l}.min.js" for l in LANGUAGES] + ["init.js"]
    print("scripts = [\n" + "".join(f'  "{s}",\n' for s in scripts) + "]")


if __name__ == "__main__":
    main()
