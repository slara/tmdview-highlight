#!/usr/bin/env python3
"""Download a pinned highlight.js release into vendor/ and build styles.css.

Run it from the repository root after changing VERSION, LANGUAGES or THEMES, then
commit the result:  python3 scripts/vendor.py
"""

import re
import urllib.request
from pathlib import Path

VERSION = "11.12.0"
# Added on top of the ~40 languages in the standard highlight.min.js build.
LANGUAGES = [
    "clojure", "dockerfile", "elixir", "erlang", "fsharp", "groovy", "haskell", "julia",
    "latex", "nginx", "nix", "ocaml", "powershell", "protobuf", "scala",
]

HLJS = f"https://cdn.jsdelivr.net/npm/@highlightjs/cdn-assets@{VERSION}"
CATPPUCCIN = "https://cdn.jsdelivr.net/npm/@catppuccin/highlightjs@1.0.1"
# Each theme's stylesheets for light and dark pages. init.js lists the same names.
THEMES = {
    "github": (f"{HLJS}/styles/github.min.css", f"{HLJS}/styles/github-dark.min.css"),
    "catppuccin": (f"{CATPPUCCIN}/css/catppuccin-latte.css", f"{CATPPUCCIN}/css/catppuccin-mocha.css"),
    "atom-one": (f"{HLJS}/styles/atom-one-light.min.css", f"{HLJS}/styles/atom-one-dark.min.css"),
    "tokyo-night": (f"{HLJS}/styles/tokyo-night-light.min.css", f"{HLJS}/styles/tokyo-night-dark.min.css"),
}
ROOT = Path(__file__).resolve().parent.parent


def fetch(url: str) -> str:
    with urllib.request.urlopen(url) as response:
        return response.read().decode("utf-8")


def scope(css: str, prefix: str) -> str:
    """Prefix every selector in a flat (no @-rules) stylesheet."""
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    rules = []
    for selectors, body in re.findall(r"([^{}]+)\{([^{}]*)\}", css):
        scoped = ", ".join(f"{prefix} {s.strip()}" for s in selectors.split(","))
        rules.append(f"{scoped} {{{body}}}")
    return "\n".join(rules)


def main() -> None:
    vendor = ROOT / "vendor"
    (vendor / "languages").mkdir(parents=True, exist_ok=True)
    (vendor / "highlight.min.js").write_text(fetch(f"{HLJS}/highlight.min.js"))
    for lang in LANGUAGES:
        (vendor / "languages" / f"{lang}.min.js").write_text(fetch(f"{HLJS}/languages/{lang}.min.js"))
    (vendor / "LICENSE").write_text(fetch(f"{HLJS}/LICENSE"))
    (vendor / "LICENSE-catppuccin").write_text(fetch(f"{CATPPUCCIN}/LICENSE"))

    parts = [
        f"/* highlight.js {VERSION} themes, one per data-code-theme, each in tmdview's light and dark theme. */",
        "/* Generated by scripts/vendor.py; don't edit by hand. */",
    ]
    for name, (light, dark) in THEMES.items():
        root = f':root[data-code-theme="{name}"]'
        dark_css = fetch(dark)
        parts += [
            scope(fetch(light), f"{root} pre.tmdview-plugin"),
            # Dark when the page is forced dark, or when the system is dark and light isn't forced.
            "@media (prefers-color-scheme: dark) {",
            scope(dark_css, f'{root}:not([data-theme="light"]) pre.tmdview-plugin'),
            "}",
            scope(dark_css, f'{root}[data-theme="dark"] pre.tmdview-plugin'),
        ]
    # Keep tmdview's own code block background and padding.
    parts.append("pre.tmdview-plugin code.hljs { background: transparent !important; padding: 0 !important; }")
    (ROOT / "styles.css").write_text("\n".join(parts) + "\n")

    scripts = ["vendor/highlight.min.js"] + [f"vendor/languages/{l}.min.js" for l in LANGUAGES] + ["init.js"]
    print("scripts = [\n" + "".join(f'  "{s}",\n' for s in scripts) + "]")


if __name__ == "__main__":
    main()
